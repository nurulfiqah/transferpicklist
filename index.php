// Stats
$stats = array('draft' => 0, 'published' => 0, 'completed' => 0);
$stmt  = $conn->prepare("SELECT status, COUNT(*) as total FROM transferpicklist_picklist GROUP BY status");
if ($stmt) {
    $stmt->execute();
    $res = $stmt->get_result();
    if ($res) {
        while ($r = $res->fetch_assoc()) {
            $stats[$r['status']] = $r['total'];
        }
    }
    $stmt->close();
}


// Pick list table
$picklists = false;
$stmt = $conn->prepare("
    SELECT p.*,
        COALESCE(c.item_count, 0)           as item_count,
        COALESCE(c.done_count, 0)           as done_count,
        COALESCE(c.confirm_return_count, 0) as confirm_return_count
    FROM transferpicklist_picklist p
    -- One pass over transferpicklist_item for all pick lists, instead of three
    -- correlated COUNT(*) subqueries per pick list.
    LEFT JOIN (
        SELECT picklist_id,
            COUNT(*) as item_count,
            SUM(status = 'transferred') as done_count,
            SUM(priority_type = 'warehouse' AND return_confirmed = 1 AND recycle = 0) as confirm_return_count
        FROM transferpicklist_item
        GROUP BY picklist_id
    ) c ON c.picklist_id = p.id
    ORDER BY p.timestamp DESC
");
if ($stmt) {
    $stmt->execute();
    $picklists = $stmt->get_result();
    $stmt->close();
}
